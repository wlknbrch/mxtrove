// Offline reference helpers for cross-platform contract tests, not production service code.
export function normalizeFixtureError(input) {
  let kind = "unknown";
  const safe = input.operation === "safe_read";
  if (input.cancelled) kind = "cancelled";
  else if (input.requiresReauth) kind = "reauth_required";
  else if (input.shareUnavailable) kind = "share_unavailable";
  else if (input.status === 401) kind = "auth_required";
  else if (input.status === 403 || input.code === "42501") kind = "forbidden";
  else if ([404, 410].includes(input.status)) kind = "unavailable";
  else if (input.status === 413) kind = "payload_too_large";
  else if (input.status === 415) kind = "unsupported_media";
  else if ([400, 422].includes(input.status)) kind = "validation";
  else if (input.status === 409) kind = "conflict";
  else if (input.status === 429) kind = "rate_limited";
  else if (input.networkFailure || [502, 503, 504].includes(input.status)) kind = "transient";
  return {
    kind,
    retryable: safe && ["rate_limited", "transient"].includes(kind),
    outcomeUnknown: !input.cancelled && !safe && Boolean(input.networkFailure || input.status >= 500),
  };
}

// Implements only the schema subset generated by mobile-contract-wire.mjs.
// A platform consumer may use a complete JSON Schema 2020-12 validator instead.
export function assertFixtureSchema(schema, value, document, name = "payload") {
  const fail = (detail) => { throw new Error(`${name}: ${detail}`); };
  if (schema === true) return;
  if (schema === false) fail("unexpected item");
  if (schema.$ref) {
    const resolved = schema.$ref.split("/").slice(1).reduce((node, key) => node?.[key], document);
    if (!resolved) fail(`unresolved ref ${schema.$ref}`);
    return assertFixtureSchema(resolved, value, document, name);
  }
  if (schema.anyOf) {
    for (const option of schema.anyOf) {
      try { assertFixtureSchema(option, value, document, name); return; } catch { /* try next branch */ }
    }
    fail("no union branch matches");
  }
  if (schema.const !== undefined && value !== schema.const) fail("wrong constant");
  if (schema.enum && !schema.enum.includes(value)) fail("unknown enum literal");
  const type = value === null ? "null" : Array.isArray(value) ? "array" : typeof value;
  if (schema.type && schema.type !== type && !(schema.type === "integer" && type === "number" && Number.isSafeInteger(value))) fail(`expected ${schema.type}, got ${type}`);
  if (type === "number" && (!Number.isFinite(value) || (schema.minimum !== undefined && value < schema.minimum) || (schema.maximum !== undefined && value > schema.maximum))) fail("number out of bounds");
  if (schema.type === "object") {
    for (const required of schema.required ?? []) if (!(required in value)) fail(`missing ${required}`);
    for (const [key, item] of Object.entries(value)) {
      if (schema.properties?.[key]) assertFixtureSchema(schema.properties[key], item, document, `${name}.${key}`);
      else if (schema.additionalProperties && typeof schema.additionalProperties === "object") assertFixtureSchema(schema.additionalProperties, item, document, `${name}.${key}`);
      else if (schema.additionalProperties === false) fail(`unexpected ${key}`);
    }
  }
  if (schema.type === "array") {
    if (value.length < (schema.minItems ?? 0) || value.length > (schema.maxItems ?? Infinity)) fail("wrong array length");
    value.forEach((item, index) => assertFixtureSchema(schema.prefixItems?.[index] ?? schema.items ?? {}, item, document, `${name}[${index}]`));
  }
  if (type === "string" && schema.pattern && !new RegExp(schema.pattern).test(value)) fail("pattern mismatch");
  if (type === "string" && schema.format === "uuid" && !/^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(value)) fail("invalid UUID");
  if (type === "string" && schema.format === "uri") { try { new URL(value); } catch { fail("invalid URI"); } }
}
